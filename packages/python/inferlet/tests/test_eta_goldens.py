def _epilogue_bytes(body) -> bytes:
    vocab = 32_000
    tok = ch_new([1], dtype.i32)
    indptr_ch = ch_from([0, 1], dtype.u32)
    out = ch_new([vocab], dtype.bool)
    host_put(tok, [1], dtype.i32)
    b = Builder(vocab, 16)
    b.set_outputs(logits_decl(vocab))
    b.bind_port(Port.EMBED_TOKENS, tok)
    b.bind_port(Port.EMBED_INDPTR, indptr_ch)
    b.stage(Stage.EPILOGUE, lambda: out.put_tensor(body(intrinsics.output(0, "logits"))))
    return b.build().encode()


def test_comparison_operators_are_the_free_functions():
    """`t < x` etc. emit exactly what `lt(t, x)` emits, in both operand
    orders (Python reflects `x < t` into `t.__gt__(x)`)."""
    assert _epilogue_bytes(lambda l: l < 0.5) == _epilogue_bytes(lambda l: lt(l, 0.5))
    assert _epilogue_bytes(lambda l: l >= 0.5) == _epilogue_bytes(lambda l: ge(l, 0.5))
    assert _epilogue_bytes(lambda l: 0.5 < l) == _epilogue_bytes(lambda l: gt(l, 0.5))
    assert _epilogue_bytes(lambda l: 0.5 >= l) == _epilogue_bytes(lambda l: le(l, 0.5))
    # `==` stays identity, so a Tensor can key a dict / sit in a set.
    t = Tensor.constant(1)
    assert {t: "x"}[t] == "x" and t != Tensor.constant(1)


def test_diffusion_step_matches_rust():
    """`inferlet_goldens.rs::diffusion_step` — the diffusion-baseline denoise
    epilogue through `eta.diffusion.{entropy_bound_accept, stable_and_confident}`."""
    from inferlet.eta.diffusion import entropy_bound_accept, stable_and_confident

    length, taps, base = 8, 4, 5
    end = base + length
    bound, confidence = 0.5, 0.1
    toks = ch_from([(i * 7919) % 1000 for i in range(length)], dtype.i32)
    embed_indptr = ch_from([0, length], dtype.u32)
    positions = ch_from(range(base, end), dtype.u32)
    kv_len = ch_from([end], dtype.u32)
    readout = ch_from(range(length), dtype.u32)
    temp = ch_from([1.0], dtype.f32)
    rng_state = ch_from([7, 0], dtype.u32)
    history = ch_from([-1] * length, dtype.i32)
    canvas_out = ch_new([length], dtype.i32)
    argmax_out = ch_new([length], dtype.i32)
    stop = ch_new([1], dtype.bool)
    mean_out = ch_new([1], dtype.f32)
    tap_ids_out = ch_new([length, taps], dtype.u32)
    tap_weights_out = ch_new([length, taps], dtype.f32)

    b = Builder(VOCAB, PAGE)

    b.set_outputs(logits_decl(VOCAB))
    for port, c in [
        (Port.EMBED_TOKENS, toks), (Port.EMBED_INDPTR, embed_indptr), (Port.KV_LEN, kv_len),
        (Port.POSITIONS, positions), (Port.READOUT, readout),
    ]:
        b.bind_port(port, c)

    def epilogue():
        positions.put_tensor(positions.take())
        r = rng_state.take()
        t = reshape(temp.read(), [])
        logits = intrinsics.output(0, "logits")
        scaled = logits / t
        probs = softmax(scaled)
        h = entropy(probs)
        sampled = gumbel_max(scaled, r)
        argmax = reduce_argmax(scaled)
        accept = entropy_bound_accept(h, bound)
        r_noise = r + iota(2)
        noise = cast(rng(r_noise, [length]) * float(VOCAB), dtype.i32)
        nxt = select(accept, sampled, noise)
        previous = history.take()
        history.put_tensor(argmax)
        done = stable_and_confident(argmax, previous, h, confidence)
        tap_weights, tap_ids = top_k(probs, taps)
        tap_ids_out.put_tensor(tap_ids)
        tap_weights_out.put_tensor(tap_weights)
        canvas_out.put_tensor(nxt)
        argmax_out.put_tensor(argmax)
        stop.put_tensor(reshape(done, [1]))
        mean_out.put_tensor(reshape(reduce_sum(h) / float(length), [1]))
        rng_state.put_tensor(r_noise + iota(2))

    b.stage(Stage.EPILOGUE, epilogue)
    for c in (canvas_out, argmax_out, stop, mean_out, tap_ids_out, tap_weights_out):
        c.note_host_take()
    check("diffusion_step", b.build())


def test_beam_step_matches_rust():
    """`inferlet_goldens.rs::beam_step` — beam-search's epilogue: the `mask` port,
    `from_shaped`, `capacity`, `top_k` / `gather` / `or_` over `[B, V]`."""
    B = 2
    pool_len = 8 * PAGE
    v = VOCAB
    init_mask = [p == 0 for _ in range(B) for p in range(pool_len)]
    mask = DslChannel.from_const(ConstData(shape_of([B, pool_len]), Dtype.BOOL, pack_elems(init_mask, Dtype.BOOL)))
    scores = ch_from([0.0, float("-inf")], dtype.f32)
    toks = ch_from([1] * B, dtype.i32)
    pos = ch_from([0] * B, dtype.u32)
    fill = ch_from([1], dtype.u32)
    klen = ch_from([1] * B, dtype.u32)
    slots = ch_from([0] * B, dtype.u32)
    lanes_b = ch_from(range(B + 1), dtype.u32)
    out = ch_new([B], dtype.i32).capacity(8)
    out_par = ch_new([B], dtype.u32).capacity(8)
    out_scr = ch_new([B], dtype.f32).capacity(8)
    out_greedy = ch_new([B], dtype.i32).capacity(8)

    b = Builder(VOCAB, PAGE)

    b.set_outputs(logits_decl(VOCAB))
    for port, c in [
        (Port.KV_LEN, klen), (Port.POSITIONS, pos), (Port.SLOTS, slots), (Port.ATTN_MASK, mask),
        (Port.EMBED_TOKENS, toks), (Port.EMBED_INDPTR, lanes_b),
    ]:
        b.bind_port(port, c)

    def epilogue():
        logits = reshape(intrinsics.output(0, "logits"), [B, v])
        cand = broadcast(reshape(scores.take(), [B, 1]), [B, v]) + log_softmax(logits)
        s, i = top_k(reshape(cand, [B * v]), B)
        parent = i // v
        tok_i = cast(i % v, dtype.i32)
        base = fill.take()
        lane = iota(B)
        base_b = broadcast(reshape(base, [1]), [B])
        wpos = base_b + lane
        inherited = gather(mask.take(), parent)
        col = broadcast(reshape(iota(pool_len), [1, pool_len]), [B, pool_len])
        wpos_b = broadcast(reshape(wpos, [B, 1]), [B, pool_len])
        newpos = eq(col, wpos_b)
        mask.put_tensor(or_(inherited, newpos))
        slots.put_tensor(wpos)
        filled = base + B
        klen.put_tensor(broadcast(reshape(filled, [1]), [B]))
        pos.put_tensor(pos.take() + 1)
        fill.put_tensor(filled)
        scores.put_tensor(s)
        toks.put_tensor(tok_i)
        out.put_tensor(tok_i)
        out_par.put_tensor(parent)
        out_scr.put_tensor(s)
        out_greedy.put_tensor(reshape(reduce_argmax(logits), [B]))

    b.stage(Stage.EPILOGUE, epilogue)
    check("beam_step", b.build())


def test_latent_step_matches_rust():
    """`inferlet_goldens.rs::latent_step` — the image sampler's epilogue: the
    `velocity` output, an `N(0, 1)` draw, and the `sin`/`cos`/`sqrt`/`rsqrt`
    ops. The one golden that carries tags 0x08..0x0b, `RngKind.NORMAL` and
    `Intrinsic.VELOCITY`, so a port that drifts on any of them fails here."""
    rows, channels = 8, 16
    tok = ch_from([1], dtype.i32)
    indptr_ch = ch_from([0, 1], dtype.u32)
    readout = ch_from(range(rows), dtype.u32)
    kv_len = ch_from([rows], dtype.u32)
    positions = ch_from(range(rows), dtype.u32)
    latent = ch_new([rows, channels], dtype.f32)
    dsigma = ch_from([-0.25], dtype.f32)
    rng_ch = ch_from([9, 0], dtype.u32)
    out = ch_new([rows, channels], dtype.f32)
    norm_out = ch_new([rows], dtype.f32)
    host_put(latent, [0.0] * (rows * channels), dtype.f32)

    b = Builder(VOCAB, PAGE)

    b.set_outputs([[decl("velocity", Axis.ROW, channels, False)]])
    for port, c in [
        (Port.EMBED_TOKENS, tok), (Port.EMBED_INDPTR, indptr_ch), (Port.KV_LEN, kv_len),
        (Port.POSITIONS, positions), (Port.READOUT, readout),
    ]:
        b.bind_port(port, c)

    def epilogue():
        positions.put_tensor(positions.take())
        v = intrinsics.output_rows(0, "velocity", rows)
        x = latent.take()
        d = reshape(dsigma.read(), [])

        square = mul(v, v)
        energy = reduce_sum(square)
        norm = sqrt(energy)
        guarded = add(energy, 1.0e-12)
        inverse = rsqrt(guarded)
        column = reshape(inverse, [rows, 1])
        spread = broadcast(column, [rows, channels])
        unit = mul(v, spread)

        ramp = cast(iota(channels), dtype.f32)
        ramp_row = reshape(ramp, [1, channels])
        ramp_plane = broadcast(ramp_row, [rows, channels])
        angle = mul(ramp_plane, d)
        sine = sin(angle)
        cosine = cos(angle)
        embedding = add(sine, cosine)

        r = rng_ch.take()
        z = normal(r, [rows, channels])
        drift = add(unit, embedding)
        step = mul(drift, d)
        jitter = mul(z, d)
        moved = add(x, step)
        stepped = add(moved, jitter)

        latent.put_tensor(stepped)
        out.put_tensor(stepped)
        norm_out.put_tensor(norm)
        rng_ch.put_tensor(add(r, iota(2)))

    b.stage(Stage.EPILOGUE, epilogue)
    out.note_host_take()
    norm_out.note_host_take()
    check("latent_step", b.build())


def test_vae_readback_matches_rust():
    """`inferlet_goldens.rs::vae_readback`: the one golden reading a voxel output."""
    rows, rgb = 16, 3
