"""
Byte-identity of the Python ETA port against the Rust SDK.

`goldens/eta_containers.txt` holds, per program, the FNV-1a identity hash and
the canonical container bytes as the Rust `eta-dsl` `Builder` emits them
(regenerated by `crates/eta-dsl/tests/sdk_goldens.rs`). Each test below
rebuilds the same program through the Python `Builder` and compares bytes —
the whole point of the port is that a Python inferlet and a Rust inferlet
tracing the same pass share one container hash and one program-cache entry.

These drive the neutral `Builder` directly, so no WIT stubs are needed.
"""

