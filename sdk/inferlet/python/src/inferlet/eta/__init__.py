"""
`inferlet.eta` — the ETA authoring surface for Python inferlets: the tracing
eDSL (`Tensor` + ops), the container encoder, and the WIT bridge
(`Channel`, `WorkingSet`, `ForwardPass`, `Pipeline`, `run_ahead`).

A stage body is an ordinary Python function traced once at first submit::

    from inferlet.eta import *

    tok_out = Channel([1], dtype.i32).named("tok_out")

    @fwd.epilogue
    def _():
        tok_out.put(reshape(reduce_argmax(intrinsics.logits()), [1]))

The emitted container bytes are identical to the Rust SDK's for the same
program, so a Python and a Rust inferlet share the host's program cache.
"""

