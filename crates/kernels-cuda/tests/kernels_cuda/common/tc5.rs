#![allow(dead_code)]

use super::Lcg;
use kernels_cuda::linear::gemm_sm100::{Elem, atom_bytes, atom_offset};

impl Side {
    /// The scale atoms with row `r` placed at atom row `at(r)`, in a tensor
    /// of `rows` atom rows.
    pub fn atoms_at(&self, k: usize, rows: usize, at: impl Fn(usize) -> usize) -> Vec<u8> {
        let gran = self.scales.as_ref().expect("scaled").2;
        let cols = k.div_ceil(gran);
        let mut atoms = vec![0u8; atom_bytes(rows, k, gran)];
        for (i, &code) in self.codes.iter().enumerate() {
            atoms[atom_offset(at(i / cols), i % cols, cols)] = code;
        }
        atoms
    }
}

/// fp8 e4m3, finite codes only.
pub fn e4m3(code: u8) -> f32 {
    let sign = if code & 0x80 != 0 { -1.0 } else { 1.0 };
    let exp = i32::from((code >> 3) & 0xf);
    let man = f32::from(code & 7);
    sign * if exp == 0 {
        man / 8.0 * 2f32.powi(-6)
    } else {
        (1.0 + man / 8.0) * 2f32.powi(exp - 7)
    }
}

pub fn e2m1(code: u8) -> f32 {
    const MAG: [f32; 8] = [0.0, 0.5, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0];
    let v = MAG[usize::from(code & 7)];
    if code & 8 != 0 { -v } else { v }
}

pub fn ue8m0(code: u8) -> f32 {
    2f32.powi(i32::from(code) - 127)
}

/// One operand: its device bytes, its decoded values, and its scales.
pub struct Side {
    pub bytes: Vec<u8>,
    pub values: Vec<f32>,
    pub scales: Option<(Vec<u8>, Vec<f32>, usize)>,
    /// The scale codes row by row, `k.div_ceil(gran)` a row.
    pub codes: Vec<u8>,
}

impl Side {
    pub fn value(&self, row: usize, k: usize, kk: usize) -> f32 {
        let v = self.values[row * k + kk];
        match &self.scales {
            Some((_, s, gran)) => v * s[row * k.div_ceil(*gran) + kk / gran],
            None => v,
        }
    }
}

/// splitmix64: every bit of a code is drawn, where `Lcg::unit` keeps only
/// a bf16's worth.
pub fn random(state: &mut u64) -> u32 {
    *state = state.wrapping_add(0x9e37_79b9_7f4a_7c15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    (z ^ (z >> 31)) as u32
}

pub fn side(
    lcg: &mut Lcg,
    bits: &mut u64,
    elem: Elem,
    gran: Option<usize>,
    rows: usize,
    k: usize,
) -> Side {
    let mut bytes = Vec::new();
    let mut values = Vec::with_capacity(rows * k);
    match elem {
        Elem::Bf16 => {
            let (raw, exact) = lcg.row(rows * k);
            bytes = raw.iter().flat_map(|v| v.to_le_bytes()).collect();
            values = exact;
        }
        Elem::E4m3 => {
            // Exponents 2^-4..2^3 keep one product from drowning the rest.
            for _ in 0..rows * k {
                let r = random(bits);
                let code = ((r & 0x80) | ((3 + (r >> 8) % 8) << 3) | (r >> 16) & 7) as u8;
                bytes.push(code);
                values.push(e4m3(code));
            }
        }
        Elem::U4 => unreachable!("affine weights are W4A16's, generated by its own test"),
        Elem::E2m1 => {
            bytes = vec![0u8; rows * k / 2];
            for i in 0..rows * k {
                let code = (random(bits) & 0xf) as u8;
                bytes[i / 2] |= code << (4 * (i % 2));
                values.push(e2m1(code));
            }
        }
    }
    let mut codes = Vec::new();
    let scales = gran.map(|gran| {
        let cols = k.div_ceil(gran);
        let mut atoms = vec![0u8; atom_bytes(rows, k, gran)];
        let mut decoded = Vec::with_capacity(rows * cols);
        for r in 0..rows {
            for c in 0..cols {
                let (code, value) = if gran == 16 {
                    let code = 0x28 + (random(bits) % 0x20) as u8;
                    (code, e4m3(code))
                } else {
                    let code = 121 + (random(bits) % 12) as u8;
                    (code, ue8m0(code))
                };
                atoms[atom_offset(r, c, cols)] = code;
                codes.push(code);
                decoded.push(value);
            }
        }
        (atoms, decoded, gran)
    });
    Side {
        bytes,
        values,
        scales,
        codes,
    }
}
