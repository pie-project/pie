//! The layers hold with no CUDA anywhere.
//!
//! This target runs with **no features**, which is the whole claim: layers 1
//! and 2 are a table and some text, so they compile and answer on a machine
//! with no toolkit, no driver and no device. That is not a convenience — it is
//! what lets `model-compiler` depend on this crate unconditionally and still
//! run in a container that has never seen a GPU.
//!
//! Everything here would also pass as a unit test inside the crate. It is a
//! separate target on purpose: a unit test compiles with whatever features the
//! rest of the build turned on, and an integration target compiled by
//! `cargo test -p kernels-cuda-new` with no flags is the only place the
//! feature-free build is actually EXERCISED rather than merely permitted.

use kernels_cuda_new::{device, execution, source, table, unit};

/// Layer 1 arrived, and a symbol names one row.
#[test]
fn the_table_is_readable_without_a_gpu() {
    assert!(!table::KERNELS.is_empty(), "the table did not come across");
    let row = &table::KERNELS[0];
    assert_eq!(table::sig(row.symbol).map(|r| r.symbol), Some(row.symbol));
}

/// Layer 2's text is in the binary, not on the disk.
///
/// The bytes are here at all only because [`include_str!`] put them here at
/// build time. A version of this crate that read `csrc/` at run time would
/// pass every other test in the tree and fail the one thing the design is
/// arranged around, so the assertion is on the CONTENT: the prelude has to
/// contain the type the rows instantiate at.
#[test]
fn the_device_sources_are_carried_in_the_binary() {
    let prelude = source::DEVICE_HEADERS
        .iter()
        .find(|h| h.name == "pie_device.cuh")
        .expect("the prelude is the one header every other entry includes");
    assert!(prelude.text.contains("bf16"), "the prelude does not define the rows' element type");

    assert!(source::roots::NORM_ALTUP_AUX.contains("__global__"));
    assert!(source::roots::NORM_ELEMENTWISE.contains("__global__"));
}

/// Every `#include` reachable from a unit resolves against the set.
///
/// NVRTC resolves against `headers[]`/`includeNames[]` and nothing else — there
/// is no include path — so a directive naming a header the set does not carry
/// compiles nowhere. Without this check that is an NVRTC error on a machine
/// with a GPU, which is the slowest possible place to find out.
///
/// **Reachability, not membership.** The set is generated by walking `csrc/`
/// and the sibling kernel tree, and that tree holds `.cuh` files belonging to
/// the ahead-of-time build — some of which include a host `.hpp` the JIT
/// deliberately does not carry. Those are harmless: NVRTC reads only what is
/// included, so a carried header no unit reaches is dead weight rather than a
/// defect. What must hold is that from a unit's root, every include resolves,
/// transitively — which is exactly what breaks a fire.
#[test]
fn every_include_reachable_from_a_unit_resolves() {
    let carried = |name: &str| source::DEVICE_HEADERS.iter().find(|h| h.name == name);

    for u in unit::UNITS {
        let mut seen: Vec<&str> = Vec::new();
        let mut queue: Vec<(&str, &str)> = vec![(u.name, u.root)];
        while let Some((from, text)) = queue.pop() {
            for included in source::quoted_includes(text) {
                let Some(header) = carried(included) else {
                    panic!("unit `{}` reaches `{included}` from `{from}`, uncarried", u.name);
                };
                if !seen.contains(&header.name) {
                    seen.push(header.name);
                    queue.push((header.name, header.text));
                }
            }
        }
    }
}

/// A unit's rows all claim the unit's own file.
///
/// The row states its file and the unit states its root; if the two can
/// disagree then a kernel is compiled by one unit and looked for in another,
/// and the symptom is a missing entry rather than anything that names the
/// mistake.
///
/// # A unit name is the file's stem, OR the stem plus a lattice suffix
///
/// Every unit was 1:1 with a `.cuh` until `crate::families::fa2`, which is 56
/// units over ONE root: `attn/fa2.cuh` compiled at 56 different points of a
/// four-axis instantiation lattice. The equality this test used to assert was
/// a proxy for the real property, and the real property is checked by
/// `a_symbol_belongs_to_one_unit` below — one symbol, at most one unit.
///
/// So the stem is derived from the ROW's file and the unit name must equal it
/// or extend it with `_`. That admits `attn/fa2.cuh` under
/// `attn/fa2_decode_hd128_g4` and still rejects a row from another file
/// entirely, which is the mistake the test was written for. It does NOT
/// admit a stem match by prefix alone: `attn/attention_flashinfer` matches its
/// own file exactly and is not confused with `attn/attention.cuh`, because
/// the stem comes from the file and not from splitting the name.
#[test]
fn a_row_lives_in_the_unit_that_compiles_it() {
    for u in unit::UNITS {
        for row in u.rows {
            let Some(file) = row.sig.file else {
                panic!("{} is in unit {} and claims no file", row.sig.symbol, u.name);
            };
            let stem = file.strip_suffix(".cuh").unwrap_or(file);
            let lattice = format!("{stem}_");
            assert!(
                u.name == stem || u.name.starts_with(&lattice),
                "{} is in unit {} and claims {:?}",
                row.sig.symbol,
                u.name,
                row.sig.file
            );
        }
    }
}

/// `unit_of` is a function: one symbol, at most one unit.
#[test]
fn a_symbol_belongs_to_one_unit() {
    for row in unit::rows() {
        let hosts: Vec<&str> =
            unit::UNITS.iter().filter(|u| u.hosts(row.sig.symbol)).map(|u| u.name).collect();
        assert_eq!(hosts.len(), 1, "{} is hosted by {hosts:?}", row.sig.symbol);

        let (index, found) = unit::unit_of(row.sig.symbol).expect("some unit hosts it");
        assert_eq!(found.name, hosts[0]);
        assert_eq!(unit::UNITS[index].name, found.name, "the index reaches the unit it named");
    }
    assert!(unit::unit_of("norm::a_kernel_nobody_wrote").is_none());
}

/// The cubin cache key spans everything that produced the cubin.
///
/// `driver-cuda/src/program/cache.rs` records this in the past tense: a cubin
/// keyed on less than what produced it is served after the thing it was not
/// keyed on changes. Under NVRTC the resolved text is the root plus every
/// header that can reach it, so both halves have to be in the key, and so does
/// the architecture.
#[test]
fn the_cache_key_spans_the_header_set_and_the_arch() {
    let u = &unit::UNITS[0];
    let base = u.cache_key("sm_89");

    assert_eq!(base, u.cache_key("sm_89"), "and is stable");
    assert_ne!(base, u.cache_key("sm_90"), "the architecture is in the key");

    let doctored = [source::Header { name: "pie_device.cuh", text: "// not what it was" }];
    assert_ne!(base, u.cache_key_with("sm_89", &doctored), "the header text is in the key");
}

