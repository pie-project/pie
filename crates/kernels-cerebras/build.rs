//! The kernel library's table: every `kernels/<group>/<name>.csl`, by its
//! path without the extension, the CSL function it is called by
//! (`k_<name>`), and its text. Lands in OUT_DIR as `units.rs`.

use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=kernels");
    let kernels = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("kernels");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let mut files = Vec::new();
    walk(&kernels, &mut files);
    files.sort();
    assert!(!files.is_empty(), "no .csl under {}", kernels.display());
    let mut text = String::from(
        "// Generated by build.rs: every unit under kernels/, by path, its call name, its text.\n\
         pub static UNITS: &[(&str, &str, &str)] = &[\n",
    );
    for file in files {
        let rel = file
            .strip_prefix(&kernels)
            .expect("walk yields paths under kernels/")
            .with_extension("");
        let path = rel.to_string_lossy().replace('\\', "/");
        let stem = rel
            .file_name()
            .expect("a unit has a file name")
            .to_string_lossy();
        let abs = file.to_string_lossy().replace('\\', "/");
        text.push_str(&format!(
            "    ({path:?}, \"k_{stem}\", include_str!({abs:?})),\n"
        ));
    }
    text.push_str("];\n");
    std::fs::write(out.join("units.rs"), text).expect("OUT_DIR is writable");
}

fn walk(dir: &Path, files: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())) {
        let path = entry.expect("a directory entry").path();
        if path.is_dir() {
            walk(&path, files);
        } else if path.extension().is_some_and(|e| e == "csl") {
            files.push(path);
        } else {
            panic!("{}: only .csl units live under kernels/", path.display());
        }
    }
}
