//! The kernel library's census: every `kernels/<group>/<name>.csl` by its
//! path without the extension, its text, the units it calls into, and every
//! function it declares with its parameter formats; and the [`Kernel`] ids,
//! one per unit entry (`k_<name>`) and per `prim/` function. Lands in
//! OUT_DIR as `units.rs`.

use std::collections::BTreeSet;
use std::fmt::Write;
use std::path::{Path, PathBuf};

struct Unit {
    path: String,
    abs: String,
    text: String,
    /// The kernels it declares (its entry, or every `prim/` function):
    /// name and parameter formats (`Param` variants).
    fns: Vec<(String, Vec<&'static str>)>,
    /// Every top-level name the unit declares (functions, globals).
    names: Vec<String>,
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=kernels");
    let kernels = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("kernels");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    let mut files = Vec::new();
    walk(&kernels, &mut files);
    files.sort();
    assert!(!files.is_empty(), "no .csl under {}", kernels.display());
    let units: Vec<Unit> = files.iter().map(|f| unit(&kernels, f)).collect();

    let mut seen = BTreeSet::new();
    for u in &units {
        for n in &u.names {
            assert!(
                seen.insert(n.clone()),
                "{}: `{n}` is declared twice in the library",
                u.path
            );
        }
        let entry = entry_of(&u.path);
        assert!(
            u.path.starts_with("prim/") || u.fns.iter().any(|(f, _)| *f == entry),
            "{} declares no `fn {entry}(`",
            u.path
        );
    }
    // The units a unit calls into, past the prelude every program carries.
    let deps: Vec<Vec<usize>> = units
        .iter()
        .enumerate()
        .map(|(i, u)| {
            units
                .iter()
                .enumerate()
                .filter(|(j, d)| {
                    *j != i
                        && d.path != "prim/prelude"
                        && d.names.iter().any(|n| mentions(&code(&u.text), n))
                })
                .map(|(j, _)| j)
                .collect()
        })
        .collect();
    // The ids: each unit's entry, and every prim function.
    let mut kernels_of: Vec<(String, usize, usize)> = Vec::new();
    for (i, u) in units.iter().enumerate() {
        for (f, (name, _)) in u.fns.iter().enumerate() {
            kernels_of.push((name.clone(), i, f));
        }
    }
    kernels_of.sort();

    let mut text =
        String::from("// Generated by build.rs from kernels/: the library's census.\n\n");
    text.push_str("pub static UNITS: &[Unit] = &[\n");
    for (u, d) in units.iter().zip(&deps) {
        let _ = writeln!(
            text,
            "    Unit {{ path: {:?}, name: {:?}, text: include_str!({:?}), deps: &{d:?}, fns: &[",
            u.path,
            entry_of(&u.path),
            u.abs
        );
        for (name, params) in &u.fns {
            let params: Vec<String> = params.iter().map(|p| format!("Param::{p}")).collect();
            let _ = writeln!(
                text,
                "        Function {{ name: {name:?}, params: &[{}] }},",
                params.join(", ")
            );
        }
        text.push_str("    ] },\n");
    }
    text.push_str("];\n\n");
    text.push_str(
        "/// A kernel the library declares: a unit's entry or a `prim/` function.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n\
         pub enum Kernel {\n",
    );
    for (name, ..) in &kernels_of {
        let _ = writeln!(text, "    {},", variant(name));
    }
    text.push_str("}\n\nimpl Kernel {\n    pub const ALL: &[Kernel] = &[\n");
    for (name, ..) in &kernels_of {
        let _ = writeln!(text, "        Kernel::{},", variant(name));
    }
    text.push_str(
        "    ];\n\n    /// The unit and the function, by index into [`UNITS`].\n    \
         const fn at(self) -> (usize, usize) {\n        match self {\n",
    );
    for (name, u, f) in &kernels_of {
        let _ = writeln!(text, "            Kernel::{} => ({u}, {f}),", variant(name));
    }
    text.push_str("        }\n    }\n}\n");
    std::fs::write(out.join("units.rs"), text).expect("OUT_DIR is writable");
}

/// The function a unit at `path` is called by: `k_` and its file stem.
fn entry_of(path: &str) -> String {
    format!("k_{}", path.rsplit('/').next().expect("a path"))
}

/// `k_round_bf16` → `RoundBf16`.
fn variant(name: &str) -> String {
    name.strip_prefix("k_")
        .expect("library functions are named k_*")
        .split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn unit(kernels: &Path, file: &Path) -> Unit {
    let rel = file
        .strip_prefix(kernels)
        .expect("walk yields paths under kernels/")
        .with_extension("");
    let path = rel.to_string_lossy().replace('\\', "/");
    let text = std::fs::read_to_string(file).unwrap_or_else(|e| panic!("{path}: {e}"));
    let mut fns = Vec::new();
    let mut names = Vec::new();
    for (at, line) in text
        .match_indices('\n')
        .map(|(i, _)| i + 1)
        .chain([0])
        .map(|i| (i, &text[i..]))
    {
        let line = line.lines().next().unwrap_or("");
        if let Some(rest) = line.strip_prefix("fn ") {
            let name = ident(rest);
            names.push(name.to_string());
            // A unit's own helpers are no kernels: only its entry and the
            // prim functions are called by id, and need formats.
            if !(path.starts_with("prim/") || name == entry_of(&path)) {
                continue;
            }
            let open = at + "fn ".len() + name.len();
            assert!(
                text[open..].starts_with('('),
                "{path}: `fn {name}` is not followed by its parameters"
            );
            let close = open
                + text[open..]
                    .find(')')
                    .unwrap_or_else(|| panic!("{path}: `fn {name}(` never closes"));
            let params = text[open + 1..close]
                .split(',')
                .map(str::trim)
                .filter(|p| !p.is_empty())
                .map(|p| {
                    let ty = p.split_once(':').map_or(p, |(_, t)| t).trim();
                    param(ty).unwrap_or_else(|| {
                        panic!("{path}: `fn {name}` takes a `{ty}`, which has no table form")
                    })
                })
                .collect();
            fns.push((name.to_string(), params));
        } else if let Some(rest) = line
            .strip_prefix("var ")
            .or_else(|| line.strip_prefix("const "))
        {
            names.push(ident(rest).to_string());
        }
    }
    Unit {
        path,
        abs: file.to_string_lossy().replace('\\', "/"),
        text,
        fns,
        names,
    }
}

/// How a parameter of this CSL type is read from an op row's words.
fn param(ty: &str) -> Option<&'static str> {
    Some(match ty {
        "[*]f32" => "PtrF32",
        "[*]i32" => "PtrI32",
        "[*]u32" => "PtrU32",
        "[*]u64" => "PtrU64",
        "i32" => "I32",
        "u32" => "U32",
        "f32" => "F32",
        "bool" => "Bool",
        _ => return None,
    })
}

/// `text` without its `//` comments.
fn code(text: &str) -> String {
    text.lines()
        .map(|l| l.split_once("//").map_or(l, |(c, _)| c))
        .collect::<Vec<_>>()
        .join("\n")
}

fn ident(s: &str) -> &str {
    let end = s
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .unwrap_or(s.len());
    &s[..end]
}

/// Whether `text` names the identifier `name` (not as part of a longer one).
fn mentions(text: &str, name: &str) -> bool {
    let bytes = text.as_bytes();
    let ident = |c: u8| c.is_ascii_alphanumeric() || c == b'_';
    text.match_indices(name).any(|(start, _)| {
        let end = start + name.len();
        start.checked_sub(1).is_none_or(|i| !ident(bytes[i]))
            && (end >= bytes.len() || !ident(bytes[end]))
    })
}

fn walk(dir: &Path, files: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())) {
        let path = entry.expect("a directory entry").path();
        if path.is_dir() {
            walk(&path, files);
        } else if path.extension().is_some_and(|e| e == "csl") {
            files.push(path);
        } else {
            panic!("{}: only .csl units live under kernels/", path.display());
        }
    }
}
