// ── the generator, spelled as the oracle spells it ─────────────────────────

fn xs(s: &mut u64) -> u64 {
    *s ^= *s >> 12;
    *s ^= *s << 25;
    *s ^= *s >> 27;
    s.wrapping_mul(0x2545_F491_4F6C_DD1D)
}

/// bf16 with a WIDE exponent and a uniform sign. See the module header.
fn fill_bf16(n: usize, seed: u64) -> Vec<u16> {
    let mut s = seed | 1;
    let mut v = Vec::with_capacity(n);
    for i in 0..n {
        let u = xs(&mut s);
        if i % 17 == 16 {
            v.push(0);
            continue;
        }
        let sign = ((u >> 31) & 1) as u16;
        let exp = (110 + ((u >> 17) % 36)) as u16;
        let mant = ((u >> 3) & 0x7f) as u16;
        v.push((sign << 15) | (exp << 7) | mant);
    }
    v
}

fn fnv1a(bytes: &[u8]) -> u64 {
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    for b in bytes {
        h = (h ^ u64::from(*b)).wrapping_mul(0x100_0000_01b3);
    }
    h
}

// ── device scratch ─────────────────────────────────────────────────────────

struct Dev(*mut c_void);

impl Dev {
    fn from_u16(host: &[u16]) -> Self {
        Self::raw(host.as_ptr().cast(), host.len() * 2)
    }
    fn from_f32(host: &[f32]) -> Self {
        Self::raw(host.as_ptr().cast(), host.len() * 4)
    }
    fn raw(src: *const c_void, bytes: usize) -> Self {
        let mut p: *mut c_void = std::ptr::null_mut();
        // SAFETY: `p` is a live out-parameter; `bytes.max(16)` keeps a
        // zero-length allocation legal so a degenerate shape still has a
        // distinct, freeable pointer to hand cuBLAS.
        unsafe {
            assert_eq!(cudaMalloc(&raw mut p, bytes.max(16)), cudaError::cudaSuccess);
            if bytes > 0 {
                assert_eq!(
                    cudaMemcpy(p, src, bytes, cudaMemcpyKind::cudaMemcpyHostToDevice),
                    cudaError::cudaSuccess
                );
            }
        }
        Self(p)
    }
    fn back_u16(&self, out: &mut [u16]) {
        self.back(out.as_mut_ptr().cast(), out.len() * 2);
    }
    fn back_f32(&self, out: &mut [f32]) {
        self.back(out.as_mut_ptr().cast(), out.len() * 4);
    }
    fn back(&self, dst: *mut c_void, bytes: usize) {
        if bytes == 0 {
            return;
        }
        // SAFETY: `dst` is the caller's live buffer of `bytes`, and `self.0`
        // was allocated with at least that many.
        unsafe {
            assert_eq!(
                cudaMemcpy(dst, self.0, bytes, cudaMemcpyKind::cudaMemcpyDeviceToHost),
                cudaError::cudaSuccess
            );
        }
    }
}

impl Drop for Dev {
    fn drop(&mut self) {
        // SAFETY: `self.0` came from `cudaMalloc` and is freed exactly once.
        unsafe {
            cudaFree(self.0);
        }
    }
}

use cudarc::runtime::sys::cudaError;

fn sync() {
    // SAFETY: no preconditions.
    unsafe {
        assert_eq!(cudaDeviceSynchronize(), cudaError::cudaSuccess);
    }
}

