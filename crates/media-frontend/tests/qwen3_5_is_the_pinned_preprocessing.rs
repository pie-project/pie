//! **QWEN3.5'S PREPROCESSING, PINNED** — the campaign's goldens carried down to
//! where they run without a GPU.
//!
//! ```text
//! cargo test -p media-frontend --test qwen3_5_is_the_pinned_preprocessing
//! ```
//!
//! Three of these claims already existed in this tree and are carried rather
//! than re-derived:
//!
//! * **(a) THE RESAMPLE IS THE RESAMPLE** — `kernels-cuda/tests/tower_pos_embed.rs`'s
//!   first gate, which fires the taps against a TEXTBOOK `align_corners`
//!   bilinear resample written without reference to the helper. Up there it
//!   also proved the CUDA kernel; here it proves only the host arithmetic,
//!   which is the half this crate owns and the half that runs on any machine.
//! * **(b) THE NATIVE GRID DEGENERATES** — the same file's second gate, which
//!   is what makes multimodal §11.3's cheap path a fact about the arithmetic
//!   rather than a special case in a branch.
//! * **the merge-block-major order** — `qwen_patchify_hwc`'s loop nest, which
//!   `engine-cuda/tests/a_vision_sku_loads_and_fires_an_image.rs` transcribed a
//!   second time to build its own streams. Here it is asserted against an
//!   order written out independently below.
//!
//! The rest is new and pinned against `transformers` v5.15.1 directly:
//! `smart_resize`'s own table, the per-patch vector layout, the grid
//! arithmetic, and one real PNG through the whole pipe.

